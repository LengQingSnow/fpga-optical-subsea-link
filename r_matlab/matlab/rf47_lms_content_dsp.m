function [lane_bits,bytes,recovery,packing]=rf47_lms_content_dsp(capture,cfg)
%RF47_LMS_CONTENT_DSP Known-sequence LMS for the isolated information page.
% Uses the LMS-BTB whitened real FSE/NLMS update with capture-local PRBS31.
% Never repeats an old BER reference over unknown payload. No hardware I/O.
if nargin<2,cfg=rf47_default_config();end
validateattributes(capture.channels,{'numeric'},{'2d','real','finite'});
assert(size(capture.channels,2)==4 && capture.sampleRateHz>=8e9, ...
    'Four simultaneous XI/XQ/YI/YQ channels are required.');
assert(all(std(double(capture.channels),0,1)>1e-10), ...
    'LMS content: missing or flat input channel.');
[lane_bits,bytes,recovery,packing]=rf47_lms_content_known_decode(capture,cfg);
if recovery.crcGoodFrames==0
    error('rf47_lms_content_dsp:NoValidPayload', ...
        ['CRC-good=0; %d idle candidates, %d training symbols. ' ...
         'Held-out idle mismatch [XI XQ YI YQ]=%s (not payload BER). ' ...
         'No image/wave bytes accepted.'], ...
        recovery.candidateIdleFrames,recovery.trainingSymbols, ...
        mat2str(recovery.heldoutIdleMismatchByLane,3));
end
end
