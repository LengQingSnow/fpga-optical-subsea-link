function save_realtime_dac_ber(output_directory, state, result, reference)
%SAVE_REALTIME_DAC_BER Persist the latest XOR record and cumulative counters.

if exist(output_directory, 'dir') ~= 7
    mkdir(output_directory);
end
latest_file = fullfile(output_directory, 'realtime_dac_ber_latest.mat');
save(latest_file, 'state', 'result', 'reference', '-v7');

log_file = fullfile(output_directory, 'realtime_dac_ber_log.csv');
write_header = exist(log_file, 'file') ~= 2;
file_id = fopen(log_file, 'a');
if file_id < 0
    error('save_realtime_dac_ber:OpenLog', ...
        'Cannot open the physical BER log: %s', log_file);
end
cleanup = onCleanup(@() fclose(file_id));
if write_header
    fprintf(file_id, ['time,capture,total_errors,total_bits,total_ber,' ...
        'last_errors,last_bits,last_ber,ch1_errors,ch1_bits,' ...
        'ch2_errors,ch2_bits,ch3_errors,ch3_bits,ch4_errors,ch4_bits\n']);
end
fprintf(file_id, ['%s,%d,%.0f,%.0f,%.12g,%.0f,%.0f,%.12g,' ...
    '%.0f,%.0f,%.0f,%.0f,%.0f,%.0f,%.0f,%.0f\n'], ...
    datestr(now, 30), result.captureCount, result.totalErrors, ...
    result.totalBits, result.totalBer, result.lastErrors, result.lastBits, ...
    result.lastBer, result.totalErrorsByLane(1), result.totalBitsByLane(1), ...
    result.totalErrorsByLane(2), result.totalBitsByLane(2), ...
    result.totalErrorsByLane(3), result.totalBitsByLane(3), ...
    result.totalErrorsByLane(4), result.totalBitsByLane(4));
clear cleanup;
end
