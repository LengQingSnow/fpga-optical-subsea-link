clear;
clc;

script_dir = fileparts(mfilename('fullpath'));
addpath(script_dir);
cfg = rf47_default_config(script_dir);
data_dir_override = getenv('RF47_DATA_DIR');
if ~isempty(data_dir_override)
    cfg.dataDir = data_dir_override;
end
capture_name_override = getenv('RF47_CAPTURE_NAME');
if ~isempty(capture_name_override)
    cfg.captureName = capture_name_override;
end

fprintf('Loading the latest four-channel scope capture...\n');
capture = load_scope_capture(cfg.dataDir, cfg.captureName);
fprintf('Capture: %s, %.6g GSa/s, %d points/channel\n', ...
    capture.directory, capture.sampleRateHz / 1e9, capture.pointCount);

fprintf(['Recovering 4 Gbaud XI/XQ/YI/YQ symbols with continuous ' ...
    'clock and timing recovery...\n']);
[rx_bytes, recovery, packing] = recover_dpqpsk_capture(capture, cfg);

fprintf('Parsing 512-byte aggregate frames and UDP fragments...\n');
if isfield(cfg, 'dynamicFrameRelock') && cfg.dynamicFrameRelock
    [frames, segments] = parse_aggregate_frames_relocked(rx_bytes, cfg);
else
    [frames, segments] = parse_aggregate_frames(rx_bytes, cfg);
end
fprintf('Aggregate CRC: %d/%d good (%.3f%%)\n', sum(frames.crcOk), ...
    frames.frameCount, 100 * sum(frames.crcOk) / frames.frameCount);

fprintf('Loading the reference underwater images and earthquake waveform...\n');
references = load_reference_dataset(cfg.datasetDir);
result_dir = fullfile(cfg.dataDir, [cfg.resultPrefix '_' ...
    datestr(now, 'yyyymmdd_HHMMSS')]);

fprintf('Reassembling CRC-trusted payloads...\n');
trusted_cfg = cfg;
trusted_cfg.useBadCrcSegments = false;
[trusted_packets, trusted_udp_stats] = reassemble_udp_packets( ...
    segments, frames, trusted_cfg);
[trusted_axds, trusted_axds_stats] = parse_axds_packets( ...
    trusted_packets, trusted_cfg);
[trusted_objects, trusted_object_stats] = reassemble_axds_objects( ...
    trusted_axds);
[trusted_raw_summary, trusted_raw_details] = ...
    recover_raw_dataset_segments(segments, references, result_dir, ...
    trusted_cfg);
trusted_pipeline_stats.udp = trusted_udp_stats;
trusted_pipeline_stats.axds = trusted_axds_stats;
trusted_pipeline_stats.objects = trusted_object_stats;
trusted_summary = compare_and_save_results(trusted_objects, references, ...
    frames, recovery, packing, trusted_pipeline_stats, result_dir, ...
    trusted_cfg);
trusted_summary.axdsImage = trusted_summary.image;
trusted_summary.axdsWaveform = trusted_summary.waveform;
trusted_summary.raw = trusted_raw_summary;
if trusted_summary.image.comparedBits == 0 && ...
        trusted_raw_summary.image.comparedBits > 0
    trusted_summary.image = trusted_raw_summary.image;
end
if trusted_summary.waveform.comparedBits == 0 && ...
        trusted_raw_summary.waveform.comparedBits > 0
    trusted_summary.waveform = trusted_raw_summary.waveform;
end

best_effort_summary = struct();
best_effort_raw_summary = struct();
best_effort_objects = struct([]);
best_effort_udp_stats = struct();
best_effort_axds_stats = struct();
best_effort_object_stats = struct();
if cfg.runBestEffortAnalysis
    fprintf('Reassembling best-effort payloads from all parseable frames...\n');
    best_effort_cfg = cfg;
    best_effort_cfg.useBadCrcSegments = true;
    best_effort_dir = fullfile(result_dir, 'best_effort');
    [best_effort_packets, best_effort_udp_stats] = ...
        reassemble_udp_packets(segments, frames, best_effort_cfg);
    [best_effort_axds, best_effort_axds_stats] = parse_axds_packets( ...
        best_effort_packets, best_effort_cfg);
    [best_effort_objects, best_effort_object_stats] = ...
        reassemble_axds_objects(best_effort_axds);
    [best_effort_raw_summary, ~] = recover_raw_dataset_segments( ...
        segments, references, best_effort_dir, best_effort_cfg);
    best_effort_pipeline_stats.udp = best_effort_udp_stats;
    best_effort_pipeline_stats.axds = best_effort_axds_stats;
    best_effort_pipeline_stats.objects = best_effort_object_stats;
    best_effort_summary = compare_and_save_results( ...
        best_effort_objects, references, frames, recovery, packing, ...
        best_effort_pipeline_stats, best_effort_dir, best_effort_cfg);
    best_effort_summary.raw = best_effort_raw_summary;
end

known_frame_summary = struct();
known_frame_details = struct();
if cfg.runKnownFrameAnalysis
    fprintf(['Reconstructing deterministic aggregate-frame and AXDS ' ...
        'bytes for exact bad-frame comparison...\n']);
    [known_frame_summary, known_frame_details] = ...
        analyze_known_frame_errors(frames, segments, references, ...
        result_dir, cfg);
end

summary = trusted_summary;
summary.bestEffort = best_effort_summary;
objects = trusted_objects;
udp_stats = trusted_udp_stats;
axds_stats = trusted_axds_stats;
object_stats = trusted_object_stats;
raw_summary = trusted_raw_summary;
raw_details = trusted_raw_details;
save(fullfile(result_dir, 'analysis_workspace.mat'), 'cfg', 'capture', ...
    'recovery', 'packing', 'rx_bytes', 'frames', 'segments', ...
    'udp_stats', 'axds_stats', ...
    'object_stats', 'objects', 'raw_summary', 'raw_details', 'summary', ...
    'best_effort_udp_stats', 'best_effort_axds_stats', ...
    'best_effort_object_stats', 'best_effort_objects', ...
    'best_effort_raw_summary', 'best_effort_summary', ...
    'known_frame_summary', 'known_frame_details', ...
    '-v7.3');

fprintf('\nResults written to: %s\n', result_dir);
fprintf(['CRC-trusted underwater image: %d compared bits, %d errors, ' ...
    'BER %.3e\n'], ...
    summary.image.comparedBits, summary.image.bitErrors, summary.image.ber);
if summary.image.bitErrors == 0 && summary.image.comparedBits > 0
    fprintf('  Zero-error 95%% BER upper bound: %.3e\n', ...
        summary.image.berUpper95);
end
fprintf('  Raw-fragment coverage: %.3f%% (%d matched segments)\n', ...
    100 * raw_summary.image.coverage, raw_summary.image.matchedSegments);
fprintf(['CRC-trusted earthquake waveform: %d compared bits, %d errors, ' ...
    'BER %.3e\n'], ...
    summary.waveform.comparedBits, summary.waveform.bitErrors, ...
    summary.waveform.ber);
if summary.waveform.bitErrors == 0 && summary.waveform.comparedBits > 0
    fprintf('  Zero-error 95%% BER upper bound: %.3e\n', ...
        summary.waveform.berUpper95);
end
fprintf('  Raw-fragment coverage: %.3f%% (%d matched segments)\n', ...
    100 * raw_summary.waveform.coverage, ...
    raw_summary.waveform.matchedSegments);
if cfg.runBestEffortAnalysis
    fprintf(['Best-effort underwater image estimate: %d compared bits, ' ...
        '%d errors, BER %.3e\n'], ...
        best_effort_summary.image.comparedBits, ...
        best_effort_summary.image.bitErrors, best_effort_summary.image.ber);
    fprintf(['Best-effort earthquake waveform estimate: %d compared bits, ' ...
        '%d errors, BER %.3e\n'], ...
        best_effort_summary.waveform.comparedBits, ...
        best_effort_summary.waveform.bitErrors, ...
        best_effort_summary.waveform.ber);
end
if cfg.runKnownFrameAnalysis
    fprintf(['Known-frame comparison: %d/%d bad frames fully ' ...
        'reconstructed, %d known bits, %d errors, BER %.3e\n'], ...
        known_frame_summary.fullyReconstructedBadFrames, ...
        known_frame_summary.crcBadFrames, ...
        known_frame_summary.comparedBits, ...
        known_frame_summary.bitErrors, known_frame_summary.ber);
    fprintf(['  Bad-frame-only known-bit BER %.3e; %d bad frames ' ...
        'contain resolved image/waveform payload.\n'], ...
        known_frame_summary.badFrameBer, ...
        known_frame_summary.badFramesWithKnownPayload);
end
